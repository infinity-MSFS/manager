//! systemd user units: a socket on the sentinel port that activates the
//! manager. Everything is per user (`$XDG_CONFIG_HOME/systemd/user`,
//! `systemctl --user`), so nothing here needs elevation.

use std::path::PathBuf;
use std::process::Command;

use infinity_ipc::dto::{SupervisorMechanism, SupervisorStatus};

use crate::{Error, REMOTE_START_FLAG, Result, SENTINEL_ADDR, Verb};

/// Socket and service share a stem; that is how systemd pairs them. Names
/// are shared with v3.
///
/// The service is a template (`@`), i.e. `Accept=yes`: systemd accepts each
/// probe itself and starts one instance per connection. `Accept=no` (one
/// long-lived service) deadlocks: nothing accepts the queued connection, so
/// systemd re-triggers the service as soon as it exits, and a manager that
/// exits at once (single-instance forwarding to the running one) drives the
/// unit into `start-limit-hit`. systemd then stops the socket too, and the
/// supervisor is dead until the next login.
pub(crate) const SOCKET_UNIT: &str = "infinity-manager-launch.socket";
pub(crate) const SERVICE_UNIT: &str = "infinity-manager-launch@.service";

fn unit_dir() -> Result<PathBuf> {
    std::env::var_os("XDG_CONFIG_HOME")
        .map(PathBuf::from)
        .or_else(|| std::env::var_os("HOME").map(|h| PathBuf::from(h).join(".config")))
        .map(|base| base.join("systemd").join("user"))
        .ok_or(Error::Failed(
            "neither XDG_CONFIG_HOME nor HOME is set; nowhere to install user units".to_owned(),
        ))
}

/// The `ExecStart=` value. Also how an installed unit is judged stale: it
/// points at a different manager binary than this one.
fn exec_start() -> Result<String> {
    let exe = std::env::current_exe().map_err(|source| Error::Io {
        what: "locate this executable".to_owned(),
        source,
    })?;
    // Quoted: systemd splits on whitespace.
    Ok(format!("\"{}\" {REMOTE_START_FLAG}", exe.display()))
}

fn socket_unit_text() -> String {
    format!(
        "# Generated by Infinity Manager. Reinstall from Settings to update.\n\
         [Unit]\n\
         Description=Infinity Manager launch supervisor (in-sim wake-up)\n\
         \n\
         [Socket]\n\
         # The connection is the signal: an in-sim aircraft's relay dials\n\
         # this port when it cannot reach the manager. Nothing reads from it,\n\
         # so systemd accepts (and so consumes) each one itself.\n\
         ListenStream={SENTINEL_ADDR}\n\
         Accept=yes\n\
         \n\
         [Install]\n\
         WantedBy=sockets.target\n"
    )
}

fn service_unit_text(exec: &str) -> String {
    format!(
        "# Generated by Infinity Manager. Reinstall from Settings to update.\n\
         [Unit]\n\
         Description=Infinity Manager (started on demand by an in-sim aircraft)\n\
         \n\
         [Service]\n\
         Type=simple\n\
         # Accept=yes hands the accepted connection over as stdin. The manager\n\
         # never reads it, but stdout/stderr must be redirected explicitly or\n\
         # they inherit the socket and log into the relay's connection.\n\
         StandardInput=socket\n\
         StandardOutput=journal\n\
         StandardError=journal\n\
         ExecStart={exec}\n"
    )
}

fn write_units() -> Result<()> {
    let dir = unit_dir()?;
    std::fs::create_dir_all(&dir).map_err(|source| Error::Io {
        what: format!("create {}", dir.display()),
        source,
    })?;
    let exec = exec_start()?;
    for (name, text) in [
        (SOCKET_UNIT, socket_unit_text()),
        (SERVICE_UNIT, service_unit_text(&exec)),
    ] {
        std::fs::write(dir.join(name), text).map_err(|source| Error::Io {
            what: format!("write {name}"),
            source,
        })?;
    }
    Ok(())
}

fn remove_units() -> Result<()> {
    let dir = unit_dir()?;
    for name in [SOCKET_UNIT, SERVICE_UNIT] {
        match std::fs::remove_file(dir.join(name)) {
            Ok(()) => {}
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => {}
            Err(source) => {
                return Err(Error::Io {
                    what: format!("remove {name}"),
                    source,
                });
            }
        }
    }
    Ok(())
}

/// `systemctl --user …`, returning trimmed stdout. With `check` a non-zero
/// exit is an error; without, it is an answer (`is-active` reports
/// "inactive" that way).
fn systemctl(args: &[&str], check: bool) -> Result<String> {
    let out = Command::new("systemctl")
        .arg("--user")
        .args(args)
        .output()
        .map_err(|source| Error::Io {
            what: format!("systemctl --user {}", args.join(" ")),
            source,
        })?;
    let stdout = String::from_utf8_lossy(&out.stdout).trim().to_owned();
    if check && !out.status.success() {
        let stderr = String::from_utf8_lossy(&out.stderr).trim().to_owned();
        return Err(Error::Failed(format!(
            "systemctl --user {} failed: {}",
            args.join(" "),
            if stderr.is_empty() { stdout } else { stderr }
        )));
    }
    Ok(stdout)
}

/// Hands systemd the graphical session's environment, so a manager it
/// starts can open a window. Most desktops do this at login, not all.
/// Best effort: a headless install must not fail for want of a DISPLAY.
fn import_session_env() {
    let _ = systemctl(
        &[
            "import-environment",
            "DISPLAY",
            "WAYLAND_DISPLAY",
            "XAUTHORITY",
            "XDG_CURRENT_DESKTOP",
            "XDG_SESSION_TYPE",
        ],
        false,
    );
}

pub(crate) fn run(verb: Verb) -> Result<()> {
    match verb {
        Verb::Install | Verb::InstallAndStart | Verb::Update => {
            write_units()?;
            systemctl(&["daemon-reload"], true)?;
            import_session_env();
            // Listening now and after every login.
            systemctl(&["enable", "--now", SOCKET_UNIT], true)?;
            if verb == Verb::Update {
                systemctl(&["restart", SOCKET_UNIT], true)?;
            }
        }
        Verb::Uninstall => {
            // A socket never enabled, or already stopped, is the goal anyway.
            let _ = systemctl(&["disable", "--now", SOCKET_UNIT], false);
            remove_units()?;
            systemctl(&["daemon-reload"], true)?;
        }
        Verb::Start => {
            systemctl(&["start", SOCKET_UNIT], true)?;
        }
        Verb::Stop => {
            systemctl(&["stop", SOCKET_UNIT], true)?;
        }
    }
    Ok(())
}

pub(crate) fn status(bundled_version: String) -> Result<SupervisorStatus> {
    let dir = unit_dir()?;
    let installed = dir.join(SOCKET_UNIT).is_file() && dir.join(SERVICE_UNIT).is_file();
    let running = installed && systemctl(&["is-active", SOCKET_UNIT], false)? == "active";
    // A generated unit has no version of its own; the one way it goes stale
    // is pointing at another binary. Reporting that as a version mismatch
    // reuses the update prompt.
    let installed_version = if installed {
        let current = format!("ExecStart={}", exec_start()?);
        let on_disk = std::fs::read_to_string(dir.join(SERVICE_UNIT)).unwrap_or_default();
        Some(if on_disk.contains(&current) {
            bundled_version.clone()
        } else {
            "stale".to_owned()
        })
    } else {
        None
    };
    Ok(SupervisorStatus {
        supported: true,
        mechanism: SupervisorMechanism::SystemdUser,
        installed,
        running,
        exe_path: Some(dir.to_string_lossy().into_owned()),
        installed_version,
        bundled_version,
        bundled: true,
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn socket_unit_listens_on_the_sentinel_port() {
        let text = socket_unit_text();
        assert!(text.contains("ListenStream=127.0.0.1:9899"));
        // Load-bearing, see SOCKET_UNIT.
        assert!(text.contains("Accept=yes"));
        assert!(text.contains("WantedBy=sockets.target"));
    }

    #[test]
    fn service_unit_is_paired_with_the_socket() {
        assert_eq!(
            SOCKET_UNIT.trim_end_matches(".socket"),
            SERVICE_UNIT.trim_end_matches("@.service")
        );
        assert!(
            SERVICE_UNIT.ends_with("@.service"),
            "Accept=yes needs a template"
        );
        let text = service_unit_text("\"/usr/bin/infinity-manager\" --remote-start");
        assert!(text.contains("StandardInput=socket"));
        assert!(text.contains("StandardOutput=journal"));
        assert!(text.contains("StandardError=journal"));
        assert!(text.contains("ExecStart=\"/usr/bin/infinity-manager\" --remote-start"));
    }

    #[test]
    fn exec_start_quotes_the_binary_path() {
        let exec = exec_start().unwrap();
        assert!(exec.starts_with('"'), "{exec}");
        assert!(exec.ends_with("\" --remote-start"), "{exec}");
    }
}
